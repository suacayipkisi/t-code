/*
 * Writes src/editor/preview/entities.h (HTML5 named character references)
 * from https://html.spec.whatwg.org/entities.json.
 *
 * Written in 100% pure standard C (no GLib, no external dependencies).
 * Compile:
 *   cc -O2 -Wall -Wextra -std=c23 -o tools/gen-preview-names tools/gen-preview-names.c
 * Usage:
 *   tools/gen-preview-names [entities.json]
 */

#include <stdbool.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef struct {
  char *name;
  char *characters;
} EntityPair;

typedef struct {
  EntityPair *items;
  size_t count;
  size_t capacity;
} EntityList;

static void list_init(EntityList *l)
{
  l->items = NULL;
  l->count = 0;
  l->capacity = 0;
}

static void list_append(EntityList *l, const char *name, const char *chars)
{
  if (l->count >= l->capacity) {
    l->capacity = l->capacity ? l->capacity * 2 : 256;
    l->items = realloc(l->items, l->capacity * sizeof(EntityPair));
  }
  l->items[l->count].name = strdup(name);
  l->items[l->count].characters = strdup(chars);
  l->count++;
}

static int compare_entities(const void *a, const void *b)
{
  const EntityPair *pa = a;
  const EntityPair *pb = b;
  return strcmp(pa->name, pb->name);
}

static void print_c_string(FILE *f, const char *str)
{
  fputc('"', f);
  for (const char *p = str; *p; p++) {
    unsigned char ch = (unsigned char)*p;
    if (ch == '"' || ch == '\\')
      fprintf(f, "\\%c", ch);
    else if (ch < 0x20 || ch == 0x7F)
      fprintf(f, "\\%03o", ch);
    else
      fputc(ch, f);
  }
  fputc('"', f);
}

int main(int argc, char **argv)
{
  const char *json_path = argc > 1 ? argv[1] : "entities.json";
  FILE *f = fopen(json_path, "r");
  if (!f) {
    fprintf(stderr, "Cannot open %s\n", json_path);
    return 1;
  }

  EntityList list;
  list_init(&list);

  char line[4096];
  char current_key[256] = { 0 };

  while (fgets(line, sizeof(line), f)) {
    /* Look for "&name;": { */
    char *amp = strchr(line, '&');
    if (amp) {
      char *semi = strchr(amp, ';');
      if (semi && semi > amp) {
        size_t len = semi - (amp + 1);
        if (len < sizeof(current_key)) {
          memcpy(current_key, amp + 1, len);
          current_key[len] = '\0';
        }
      }
    }

    /* Look for "characters": "..." */
    char *chars_key = strstr(line, "\"characters\":");
    if (chars_key && current_key[0]) {
      char *q1 = strchr(chars_key + 13, '"');
      if (q1) {
        char *q2 = strchr(q1 + 1, '"');
        if (q2) {
          size_t clen = q2 - (q1 + 1);
          char chars_val[256];
          if (clen < sizeof(chars_val)) {
            memcpy(chars_val, q1 + 1, clen);
            chars_val[clen] = '\0';
            list_append(&list, current_key, chars_val);
            current_key[0] = '\0';
          }
        }
      }
    }
  }
  fclose(f);

  if (list.count == 0) {
    fprintf(stderr, "No entities found in %s\n", json_path);
    return 1;
  }

  qsort(list.items, list.count, sizeof(EntityPair), compare_entities);
  printf("Loaded and sorted %zu HTML5 entities from %s\n", list.count, json_path);

  const char *out_path = "src/editor/preview/entities.h";
  FILE *out = fopen(out_path, "w");
  if (!out) {
    perror(out_path);
    return 1;
  }

  fprintf(out, "/*\n");
  fprintf(out, " * HTML5's named character references (&name;), from https://html.spec.whatwg.org/entities.json.\n");
  fprintf(out, " * Generated by tools/gen-preview-names: do not edit. Sorted by name (strcmp) for bsearch().\n");
  fprintf(out, " */\n");
  fprintf(out, "#pragma once\n\n");
  fprintf(out, "/* clang-format off */\n\n");
  fprintf(out, "#include \"editor/preview/state.h\"\n\n");
  fprintf(out, "static const PreviewName entity_names[] = {\n");

  for (size_t i = 0; i < list.count; i++) {
    fprintf(out, "  { ");
    print_c_string(out, list.items[i].name);
    fprintf(out, ", ");
    print_c_string(out, list.items[i].characters);
    fprintf(out, " },\n");

    free(list.items[i].name);
    free(list.items[i].characters);
  }

  fprintf(out, "};\n");
  fprintf(out, "/* clang-format on */\n");
  fclose(out);

  free(list.items);
  printf("Wrote %s\n", out_path);
  return 0;
}
