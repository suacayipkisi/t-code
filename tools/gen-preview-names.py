#!/usr/bin/env python3
"""Writes the Markdown preview's name tables: src/editor/preview/entities.h (every HTML5 named
character reference, as CommonMark requires) and src/editor/preview/emoji.h (GitHub's :shortcodes:).

  curl -sSfLO https://html.spec.whatwg.org/entities.json
  curl -sSfLO https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json
  tools/gen-preview-names.py entities.json emoji.json
"""
import json
import os
import sys


def c_string(text):
    out = []
    for ch in text:
        if ch in '"\\':
            out.append("\\" + ch)
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def write(path, comment, ctype, name, pairs):
    with open(path, "w", encoding="utf-8") as f:
        f.write("/*\n * %s\n * Generated by tools/gen-preview-names.py: do not edit. Sorted by name (strcmp) for bsearch().\n */\n" % comment)
        f.write("#pragma once\n\n/* clang-format off */\n")
        f.write("static const %s %s[] = {\n" % (ctype, name))
        for key, value in pairs:
            f.write("  { %s, %s },\n" % (c_string(key), c_string(value)))
        f.write("};\n/* clang-format on */\n")


def main():
    entities_json, emoji_json = sys.argv[1], sys.argv[2]
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "editor", "preview")

    entities = json.load(open(entities_json, encoding="utf-8"))
    pairs = sorted(((k[1:-1], v["characters"]) for k, v in entities.items() if k.endswith(";")),
                   key=lambda p: p[0].encode())
    write(os.path.join(root, "entities.h"),
          "HTML5's named character references (&name;), from https://html.spec.whatwg.org/entities.json.",
          "PreviewName", "entity_names", pairs)

    emoji = json.load(open(emoji_json, encoding="utf-8"))
    pairs = sorted({(alias, e["emoji"]) for e in emoji if "emoji" in e for alias in e["aliases"]},
                   key=lambda p: p[0].encode())
    write(os.path.join(root, "emoji.h"),
          "GitHub's emoji shortcodes (:name:), from https://github.com/github/gemoji (db/emoji.json).",
          "PreviewName", "emoji_names", pairs)


if __name__ == "__main__":
    main()
